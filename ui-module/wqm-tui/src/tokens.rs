// --- §3 highlight roles -------------------------------------------------------------

/// The reserved selector hue. Cyan appears in NOTHING else: if it is a cyan block, it is
/// what you have selected. A theme slot, so a user who has retuned cyan retunes the
/// selector with it.
pub fn selector() -> Color {
    match active_theme() {
        // §15 left this field to us: `accent` or `info`. `info` is measured blue/cyan in
        // every bundled theme while `accent` swings purple→pink→cyan, and §3 reserves the
        // selector ABSOLUTELY — a selector that lands on the theme's error hue breaks the one
        // rule the whole highlight system rests on. `tokens::tests` measures the collision.
        Some(palette) => hue(palette.info),
        None => hue(Color::Cyan),
    }
}
/// Text sitting inside an inverted selector block.
pub fn selector_fg() -> Color {
    hue(Color::Black)
}

/// An inverted highlight block — a hue fill with dark text on it.
///
/// Where the encoding refuses colour, this becomes reverse video, which is what an inverted
/// block structurally *is*: the selector survives as a swapped foreground and background
/// rather than disappearing. Without it, `fill` and the text on it both resolve to
/// `Color::Reset` and a selected row becomes indistinguishable from an unselected one —
/// which is the same class of failure as [`Palette::Theme`]'s invisible cursor row.
///
/// # Under a modal there is no block at all
///
/// A fill IS the highlight, so §6 takes it whole: the block becomes bold muted text, keeping
/// its own padding so nothing on the row moves. That is the treatment the tab bar and the
/// Dashboard's cell headings each used to spell for themselves; stating it here is what lets
/// both of them stop asking whether a modal is open. Modifiers a caller adds are patched on
/// top of this style as they are on top of the fill, so a block that was bold stays bold.
pub fn inverted(fill: Color) -> Style {
    if under_modal() {
        return muted_style().add_modifier(Modifier::BOLD);
    }
    match family() {
        Family::None => Style::default().add_modifier(Modifier::REVERSED),
        _ => Style::default().fg(selector_fg()).bg(fill),
    }
}
/// The data cursor's row tint — a subtle darker fill, deliberately not an inverse block.
pub fn cursor_bg() -> Color {
    neutral(19)
}

/// The glyph a selected row wears in its gutter (Chris, 20260907, ruling 10).
///
/// A left half-block rather than a full one: it marks the row's edge without becoming a column
/// of its own, and it survives an encoding that refuses colour, which is the whole reason the
/// ruling names a glyph AND a hue rather than a hue alone.
pub const SELECTED_BAR: char = '▎';

/// The **selection** hue — the gutter bar's colour, and what the row's wash is mixed toward.
///
/// Catppuccin's `lavender` on a flavour, `secondary` on every other theme; the rule itself is
/// [`crate::categorical::selected_of`], because deciding it means knowing what a flavour is.
/// Magenta is the slot-family stand-in, chosen the way every other slot value is: a hue no role
/// in the ten already spends.
///
/// Through [`hue`] like every reserved field, so a modal takes it away with everything else
/// (VL §6) — a selection is a highlight, not a system condition.
pub fn selected() -> Color {
    match active_theme() {
        Some(palette) => hue(crate::categorical::selected_of(&palette)),
        None => hue(Color::Magenta),
    }
}

/// A selected row's fill: the terminal's own background pulled toward [`selected`] by
/// [`WASH_MIX`] — the same strength, and the same reasoning, as the unreachable-daemon wash.
///
/// # [`None`] below RGB, and the bar carries the selection alone
///
/// Only [`Family::Rgb`] can express "this background, but more lavender". A fixed substitute
/// would be a full-row fill chosen without knowing the theme's polarity, which is unreadable
/// exactly where it matters most. So below RGB this returns [`None`] and [`SELECTED_BAR`] is
/// the whole of the mark — structure first, colour reserved, which is the rule the condition
/// wash already follows.
pub fn selected_bg() -> Option<Color> {
    if family() != Family::Rgb {
        return None;
    }
    let bg = ladder_endpoints().background;
    // The same fallback shape as the condition wash: a named slot colour has no channels to mix,
    // so where the hue cannot be read as RGB the mix goes toward a written-down lavender. It is
    // reached only with no bundled theme in force, where `selected()` itself is the slot
    // stand-in — the bar is then magenta over a lavender wash, which is two stand-ins agreeing
    // about what they stand for.
    let toward = Rgb::from_color(selected()).unwrap_or(Rgb::new(0xb4, 0xbe, 0xfe));
    Some(Color::Rgb(
        mix(bg.r, toward.r, WASH_MIX),
        mix(bg.g, toward.g, WASH_MIX),
        mix(bg.b, toward.b, WASH_MIX),
    ))
}
/// The leading `▸` marker on the data cursor row.
///
/// # Under a modal it is [`muted`]
///
/// The mark sits above the muted rung to distinguish the cursor row from the rows around it,
/// which makes it one of the bright text rungs — and a bright rung is exactly what a modal
/// takes away (VL §6).
pub fn cursor_mark() -> Color {
    modal::or_muted(neutral(70))
}
/// The editing cell fill — lighter than the cursor tint, so it reads as "you type HERE".
pub fn edit_bg() -> Color {
    neutral(35)
}

