/// How neutrals are sourced. Hues are unaffected — they are always theme slots.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Palette {
    /// Only the 16 theme slots. Maximally theme-adaptive: a user who restyles their
    /// terminal restyles wqm with it, greys included. The cost is collapse — eleven
    /// specified neutrals map onto four available slots, so the emphasis ladder loses
    /// rungs and several roles that r02 separates end up sharing a colour.
    Theme,
    /// Theme slots for hues, the xterm 256-table greyscale ramp (indices 232–255) for
    /// neutrals. Still terminal-resolved indices rather than absolute RGB, and still
    /// downgrades cleanly, but the ramp is standard rather than theme-defined — so the
    /// eleven rungs survive at the price of greys that do not follow the user's theme.
    Indexed,
    /// Neutrals generated by interpolating between the terminal's *own* background and
    /// foreground, which [`crate::terminal`] asks it for.
    ///
    /// This is the only mode that answers both defects above: the endpoints carry the
    /// theme's hue, so every rung inherits it and none reads as yellow; and anchoring 0%
    /// at the real background guarantees each rung is ordered above the base rather than
    /// sinking into it.
    ///
    /// It costs the module's opening promise: these tokens **do** emit absolute RGB. The
    /// mitigation is that the values are read off the user's terminal rather than chosen
    /// here, which is arguably a stronger form of honouring a theme than picking slots
    /// from it. It also costs r02's percentages their absolute meaning — under this mode a
    /// rung is a position on the terminal's contrast range, not a byte value. Needs
    /// truecolor and a terminal that answers `OSC 11`/`OSC 10`; without both, falls back
    /// to [`ENDPOINT_FALLBACK`].
    Derived,
    /// **§15's answer, and the default.** Everything comes from the bundled theme chosen with
    /// [`set_theme`]: the neutrals interpolate between the theme's own `bg` and `fg`, and the
    /// roles are the theme's own semantic fields rather than ANSI slots.
    ///
    /// This is [`Palette::Derived`] with the endpoints handed over as *data* instead of asked
    /// of the terminal, which is why it needs no `OSC` round trip and works with no terminal
    /// at all — a capture, a pipe, a CI run. It also answers the one thing `Derived` could
    /// not: `Derived` knows the terminal's two endpoints and nothing else, so `healthy` stayed
    /// an ANSI slot and could land anywhere the user had put green. A theme names all ten.
    ///
    /// It costs what `Derived` costs — absolute RGB — plus one thing more: the screen stops
    /// being *the terminal's* and becomes the theme's. §15 accepts that explicitly (*"full
    /// paint — the theme owns the background"*, superseding r02 §6), which is why
    /// [`screen_bg`] paints under this source and under no other.
    ///
    /// With no theme chosen it is [`Palette::Derived`] exactly: the terminal's endpoints, the
    /// slot hues, and layer 0 left alone. A default has to work before anyone configures it.
    Bundled,
}

/// What [`Palette::Derived`] interpolates between when the terminal was never asked, or
/// declined to answer.
///
/// Black to white: the assumption r02 was authored under, so the fallback reproduces the
/// authored ladder rather than inventing a third one.
pub const ENDPOINT_FALLBACK: Endpoints = Endpoints {
    background: Rgb::new(0, 0, 0),
    foreground: Rgb::new(255, 255, 255),
};

/// The rung the terminal's foreground *is*.
///
/// r02 puts `normal` at grey85 and [`normal()`] renders it as `Color::Reset` — the
/// terminal's own foreground. So under [`Palette::Derived`] the foreground endpoint is the
/// 85% rung, not the 100% one, and anchoring it at 100% compresses the whole ladder
/// downward. Measured on Catppuccin Mocha, that compression cost `faint` 5, `muted` 13 and
/// `cursor_mark` 20 luma against the [`Palette::Indexed`] ramp — the gap Chris saw as "not
/// as good as Indexed" (20260730). Anchoring here restores it and lets `strong` extrapolate
/// *past* the foreground, which is what a rung above the baseline has to do.
pub(crate) const NORMAL_RUNG: u8 = 85;

static ENDPOINTS: RwLock<Endpoints> = RwLock::new(ENDPOINT_FALLBACK);

/// Installs the endpoints [`Palette::Derived`] interpolates between.
///
/// Call once at startup, before a TUI takes the terminal — see
/// [`crate::terminal::detect`]. Rendering never queries, so a frame costs no round trip.
pub fn set_endpoints(endpoints: Endpoints) {
    if let Ok(mut slot) = ENDPOINTS.write() {
        *slot = endpoints;
    }
}

/// The endpoints currently in force.
pub fn endpoints() -> Endpoints {
    ENDPOINTS.read().map(|e| *e).unwrap_or(ENDPOINT_FALLBACK)
}

/// The source in force. **`Bundled` by default** (§15): the crate ships inside `wqm`, where a
/// theme is always chosen, and the three older sources are now comparisons rather than the
/// shipping answer. The default used to be [`Palette::Theme`], which meant every frame anyone
/// judged in the pantry was rendered through the six-of-eleven rung collapse §8.5 measured.
static ACTIVE: AtomicU8 = AtomicU8::new(Palette::Bundled as u8);

impl Palette {
    /// The palette every token currently resolves against.
    pub fn current() -> Palette {
        match ACTIVE.load(Ordering::Relaxed) {
            0 => Palette::Theme,
            1 => Palette::Indexed,
            2 => Palette::Derived,
            _ => Palette::Bundled,
        }
    }

    /// Every mode, in the order the sheet compares them.
    pub const ALL: [Palette; 4] = [
        Palette::Theme,
        Palette::Indexed,
        Palette::Derived,
        Palette::Bundled,
    ];

    /// The name this mode is spelled with in the pantry and in VISUAL-LANGUAGE.md.
    pub const fn label(self) -> &'static str {
        match self {
            Palette::Theme => "Theme",
            Palette::Indexed => "Indexed",
            Palette::Derived => "Derived",
            Palette::Bundled => "Bundled",
        }
    }

    /// Switch palettes. Lets one pantry render both modes so the trade-off is judged from
    /// a pair of frames rather than from an argument.
    pub fn set(palette: Palette) {
        ACTIVE.store(palette as u8, Ordering::Relaxed);
    }

    /// The family this source *wants* to be emitted in. What it actually gets is
    /// [`family()`], which is this capped by the encoding.
    pub const fn family(self) -> Family {
        match self {
            Palette::Theme => Family::Slots,
            Palette::Indexed => Family::Ramp,
            Palette::Derived | Palette::Bundled => Family::Rgb,
        }
    }
}

/// The two colours the neutral ladder is interpolated between — **the theme's when one is
/// chosen and the source is [`Palette::Bundled`], the terminal's otherwise.**
///
/// One function rather than a branch at every call site: the ladder, the wash and the layer
/// fills all read the base, and a base read from two different places is a base that can
/// disagree with itself. It is also the whole of what `Bundled` changes about neutrals —
/// `Derived`'s interpolation is reused verbatim, which is §15's *"nothing is thrown away"*.
fn ladder_endpoints() -> Endpoints {
    match (Palette::current(), theme()) {
        (Palette::Bundled, Some(palette)) => Endpoints {
            background: Rgb::from_color(palette.bg).unwrap_or_else(|| endpoints().background),
            foreground: Rgb::from_color(palette.fg).unwrap_or_else(|| endpoints().foreground),
        },
        _ => endpoints(),
    }
}

/// The bundled theme, but only where it is the thing being rendered from.
///
/// A theme that has been *chosen* is not the same as a theme that is *in force*: the pantry
/// sets one at startup and then renders the palette comparisons, and a `Theme`-sourced frame
/// that quietly picked up the bundled hues would make that comparison a lie. So every
/// role below asks through here, and every source other than [`Palette::Bundled`] gets `None`.
///
/// Public because [`crate::styles::palette`] renders the theme's own fields, and it has to
/// obey the same rule the roles do — a vocabulary frame that showed the bundled hues while a
/// slot palette was in force would be describing a screen nobody is looking at.
pub fn active_theme() -> Option<ThemePalette> {
    match Palette::current() {
        Palette::Bundled => theme(),
        _ => None,
    }
}

/// How every token below is emitted: **the lesser of what the source wants and what the
/// encoding permits**.
///
/// This one comparison is the whole Source × Encoding split. A preference cannot exceed a
/// capability, and a capability never dictates a preference below it — asking for
/// [`Palette::Theme`] on a truecolor terminal still gets theme slots, because slots are what
/// was asked for.
///
/// Degradation drops to the next family's **own** ladder rather than approximating the one
/// above it; [`crate::encoding`] carries the measurement that forced that rule.
pub fn family() -> Family {
    Palette::current()
        .family()
        .min(Encoding::current().family())
}

/// A reserved hue — or nothing if the encoding refuses colour, or the muted rung if a modal
/// owns the input.
///
/// The design anticipates the first: r02 §3 asks for a structural signature first with colour
/// reserved, and [`Health::glyph`] already carries state as shape. So dropping the hue costs
/// emphasis, not information.
///
/// The second is VL §6, and this is the whole of its implementation. **Every** reserved hue in
/// the vocabulary is emitted through here — [`selector`], [`selector_fg`], and everything
/// [`role`] answers: [`healthy`], [`degraded`], [`offline`], [`accent`], [`in_flight`], and so
/// [`Health::color`] with them. A widget therefore cannot forget the rule, because a widget
/// never sees it; see [`modal`] for the per-widget flag this replaced and why it leaked.
fn hue(color: Color) -> Color {
    match family() {
        Family::None => Color::Reset,
        _ => modal::or_muted(color),
    }
}

/// A neutral, named by the luminance percentage r02 specifies for it.
///
/// The percentage is the authored value; [`family()`] decides which ladder it is read off.
/// [`Family::Ramp`] picks the nearest step on the xterm greyscale ramp, whose steps run
/// 8, 18, … 238 at indices 232–255; [`Family::Slots`] collapses onto the nearest of the four
/// available slots; [`Family::None`] emits nothing, leaving the cell to whatever the terminal
/// is already painting.
///
/// Note what this does *not* do: it never converts one family's answer into another's. A
/// rung is always computed from its percentage, so degrading is choosing a different ladder
/// rather than approximating the one above — see [`crate::encoding`] for the measurement.
fn neutral(percent: u8) -> Color {
    match family() {
        Family::None => Color::Reset,
        Family::Slots => match percent {
            0..=24 => Color::Black,
            25..=55 => Color::DarkGray,
            56..=92 => Color::Gray,
            _ => Color::White,
        },
        Family::Ramp => {
            let target = percent as u16 * 255 / 100;
            match target {
                // Below the ramp's first step and above its last, the cube's true black
                // and true white are the closer answers.
                0..=7 => Color::Indexed(16),
                243..=255 => Color::Indexed(231),
                _ => {
                    let step = ((target - 8) as f32 / 10.0).round() as u16;
                    Color::Indexed(232 + step.min(23) as u8)
                }
            }
        }
        Family::Rgb => match active_theme() {
            // Four anchors when the theme names four; the chord when it names two.
            Some(theme) => along_curve(percent, &theme),
            None => along_chord(percent, ladder_endpoints()),
        },
    }
}


/// The ladder as a **straight chord** between two endpoints.
///
/// What every source but [`Palette::Bundled`] gets, because two endpoints is all they have:
/// [`crate::terminal::detect`] reads `OSC 11`/`OSC 10` and that is a background and a
/// foreground, full stop.
fn along_chord(percent: u8, endpoints: Endpoints) -> Color {
    let Endpoints {
        background,
        foreground,
    } = endpoints;
    let t = percent as f32 / NORMAL_RUNG as f32;
    let raw = [
        lerp(background.r, foreground.r, t),
        lerp(background.g, foreground.g, t),
        lerp(background.b, foreground.b, t),
    ];
    into_gamut([background.r, background.g, background.b], raw)
}

/// The ladder as a **piecewise curve through all four neutrals the theme names**.
///
/// # Why a curve and not a chord (Chris, 20260801)
///
/// *"Why would they not be anchored on theme.bg/selection/muted/fg, either on two points or
/// more if possible (though I can imagine that bg/selection/muted/fg is on a curve rather than
/// a line)"* — and he is right on both counts. §15 adopted a source that names **four**
/// neutrals and the ladder was using **two**, so a theme whose interior anchors sit off the
/// chord had its own neutral character straightened out by us.
///
/// Measured as perpendicular distance from the chord in Lab: Catppuccin Mocha's anchors sit
/// essentially *on* it (ΔE 0.1 and 0.6), which is why nothing looked wrong there — but
/// Dracula's `muted` is **25.5** off it, Cyberpunk's `selection` **25.2**, Kanagawa's `muted`
/// **15.5**. That is exactly the *"error some other palettes than catppuccin might surface"*.
/// So this is a no-op where a theme is linear and a correction where it is not.
///
/// # The anchors keep their MEASURED positions, and the rungs keep r02's
///
/// An anchor sits where its luminance puts it — `selection` at 9% on Mocha, `muted` at 38% —
/// and a rung stays at the percentage r02 names it with. The curve is the map between them, so
/// this changes what colour a rung *is*, never where it sits. `neutral(NORMAL_RUNG)` still
/// lands exactly on `fg` and `neutral(0)` still lands exactly on `bg`, which is what
/// [`normal`] and [`screen_bg`] rest on.
fn along_curve(percent: u8, theme: &ThemePalette) -> Color {
    let anchors = anchors(theme);
    let p = percent as f32;

    // Past the last anchor there is nothing to interpolate toward, so `strong` continues along
    // the ladder's overall axis — see `into_gamut` for what stops it from turning warm.
    let (base, target, span_start, span_len) = match anchors
        .windows(2)
        .find(|w| p >= w[0].0 && p <= w[1].0)
    {
        Some(w) => (w[0].1, w[1].1, w[0].0, w[1].0 - w[0].0),
        None => {
            let first = anchors[0];
            let last = anchors[anchors.len() - 1];
            (first.1, last.1, first.0, last.0 - first.0)
        }
    };

    let t = if span_len > 0.0 {
        (p - span_start) / span_len
    } else {
        0.0
    };
    let raw = [
        lerp(base[0], target[0], t),
        lerp(base[1], target[1], t),
        lerp(base[2], target[2], t),
    ];
    into_gamut(base, raw)
}

/// The theme's four neutrals as `(position on r02's scale, rgb)`, in ladder order.
///
/// Positions are **measured**, not assumed: `selection` and `muted` are wherever their
/// luminance puts them, which differs per theme and is the whole reason the curve is not a
/// chord. `theme_sheet::every_theme_gives_ten_distinct_roles_and_four_ordered_neutrals`
/// guarantees they are strictly ordered inside `[bg, fg]`, so the windows below always bracket.
fn anchors(theme: &ThemePalette) -> [(f32, [u8; 3]); 4] {
    let channels = |colour: Color| match Rgb::from_color(colour) {
        Some(rgb) => [rgb.r, rgb.g, rgb.b],
        None => [0, 0, 0],
    };
    let at = |colour: Color| rung_of(colour, theme);
    [
        (0.0, channels(theme.bg)),
        (at(theme.selection), channels(theme.selection)),
        (at(theme.muted), channels(theme.muted)),
        (NORMAL_RUNG as f32, channels(theme.fg)),
    ]
}

/// Relative luminance — the measure r02 names its rungs in.
fn luminance(colour: Color) -> f32 {
    match Rgb::from_color(colour) {
        Some(rgb) => 0.2126 * rgb.r as f32 + 0.7152 * rgb.g as f32 + 0.0722 * rgb.b as f32,
        None => 0.0,
    }
}

/// Where a colour sits on r02's ladder — **measured**, not assumed.
///
/// `bg` is 0 and `fg` is [`NORMAL_RUNG`] by definition, and everything else lands wherever its
/// luminance puts it. This is the unit the design names its rungs in, so it is also the unit a
/// question like *"is this brighter than `normal`?"* has to be asked in.
///
/// Extracted because it was written out three times — inside [`anchors`], inside a test, and a
/// fourth time it was about to be written in [`crate::styles::strong`]. A measure with three
/// copies is a measure that can disagree with itself.
///
/// ⚠ **This has a direction and [`delta_e`] does not**, which is the whole reason it is here.
/// ΔE said the accent-tinted `strong` candidates were well clear of body text; they sit at rungs
/// 80 and 77 against `normal` at 85, i.e. *darker* than the text they have to out-shout. A
/// distance cannot express "brighter than".
pub(crate) fn rung_of(colour: Color, theme: &ThemePalette) -> f32 {
    let (bg, fg) = (luminance(theme.bg), luminance(theme.fg));
    if (fg - bg).abs() < f32::EPSILON {
        0.0
    } else {
        NORMAL_RUNG as f32 * (luminance(colour) - bg) / (fg - bg)
    }
}

/// Bring an extrapolated colour back into gamut **without turning it**.
///
/// # The defect this fixes, which Chris saw by eye
///
/// *"Even for catppuccin, the strong is clearly a tad warmer than all the other greys."* He was
/// right, and the cause is exact: `strong` is rung 100 on a scale whose foreground is 85, so it
/// is extrapolated *past* `fg`, and clamping each channel independently at 255 stops whichever
/// channel saturates first while the others keep climbing. Mocha's foreground is blue-tinted,
/// so **blue** hits the ceiling and red and green carry on — the loudest rung on the screen
/// drifts warm exactly where it is most visible.
///
/// Measured over the fifteen bundled themes: **8 clamp at least one channel**, and on four of
/// them the hue shift is plainly visible — Mocha ΔE 11.1, TokyoNight 12.5, RosePine 11.5,
/// GruvboxDark 5.8 (2.3 is a just-noticeable difference).
///
/// The fix keeps the *direction* and gives up only distance: if any channel overshoots, the
/// whole offset from the base is scaled back by the largest overshoot, so the result is the
/// brightest colour still on that line and in gamut. A theme whose foreground is already near
/// white loses almost nothing (Dracula ΔE 1.5); a tinted one keeps its tint.
pub(crate) fn into_gamut(base: [u8; 3], raw: [f32; 3]) -> Color {
    // How far each channel wanted to travel, and how far it *could* before hitting the wall it
    // is heading for. The ratio of the two is how much this channel overreached; the largest
    // of the three is how far back the whole offset has to be scaled.
    //
    // **The ratio is offset-to-headroom, not value-to-255**, and the difference is not
    // academic: the first version of this divided by `raw / 255` and left Dracula's `strong`
    // 3.1 units off the axis — a channel that starts at 40 and wants to reach 285 has
    // overreached by 245/215, not by 285/255. `strong_stays_on_the_themes_own_axis…` is what
    // said so, which is the whole reason it measures colinearity instead of eyeballing a hex.
    let overreach = (0..3).fold(1.0f32, |worst, i| {
        let (base, raw) = (base[i] as f32, raw[i]);
        let headroom = if raw > 255.0 {
            255.0 - base
        } else if raw < 0.0 {
            -base
        } else {
            return worst;
        };
        // A channel already at the wall cannot travel at all; nothing can be scaled to fit, so
        // leave it to the final clamp rather than dividing by zero.
        if headroom.abs() < f32::EPSILON {
            worst
        } else {
            worst.max((raw - base) / headroom)
        }
    });

    let scale = |base: u8, value: f32| {
        (base as f32 + (value - base as f32) / overreach)
            .round()
            .clamp(0.0, 255.0) as u8
    };
    Color::Rgb(
        scale(base[0], raw[0]),
        scale(base[1], raw[1]),
        scale(base[2], raw[2]),
    )
}

/// CIE76 perceptual distance — **the unit every colour distance in this crate is recorded in**.
///
/// Public to the crate because it stopped being a test-only concern: `styles::strong` needs it
/// at render time to back a candidate off the hues §3 reserves, and a second implementation of
/// a colour metric is a second set of numbers that can disagree with the documented ones. The
/// recurring bug this crate has paid for twice is a threshold compared in the wrong unit
/// (`WASH_MIX`'s 11-14 read as byte distance, a band asserted in sRGB), so there is one
/// function and the numbers in the documents all mean it.
///
/// Rule of thumb: **2.3 is a just-noticeable difference**; above 5 is plainly a different
/// colour.
///
/// CIELAB rather than sRGB bytes, so a difference between two colours can be compared to a
/// difference between two others. Byte distance cannot do that — it makes two dark colours look
/// closer than two light ones that are equally distinguishable.
pub(crate) fn lab(colour: Color) -> (f32, f32, f32) {
    let (r, g, b) = match colour {
        Color::Rgb(r, g, b) => (r as f32 / 255.0, g as f32 / 255.0, b as f32 / 255.0),
        other => panic!("expected RGB, got {other:?}"),
    };
    let linear = |u: f32| {
        if u <= 0.04045 {
            u / 12.92
        } else {
            ((u + 0.055) / 1.055).powf(2.4)
        }
    };
    let (r, g, b) = (linear(r), linear(g), linear(b));
    // sRGB → XYZ (D65), normalised by the white point.
    let x = (0.4124 * r + 0.3576 * g + 0.1805 * b) / 0.95047;
    let y = 0.2126 * r + 0.7152 * g + 0.0722 * b;
    let z = (0.0193 * r + 0.1192 * g + 0.9505 * b) / 1.08883;
    let f = |t: f32| {
        if t > 0.008856 {
            t.cbrt()
        } else {
            7.787 * t + 16.0 / 116.0
        }
    };
    let (fx, fy, fz) = (f(x), f(y), f(z));
    (116.0 * fy - 16.0, 500.0 * (fx - fy), 200.0 * (fy - fz))
}


/// Both ends of the ladder are the theme's own colours, exactly, on every theme.
///
/// [`screen_bg`] returns `bg` and [`normal`] returns `fg`, and both are *documented* as
/// landing on the anchors by construction — `NORMAL_RUNG` exists for no other reason. That
/// was true of the chord and it has to stay true of the curve, because a rounding error at
/// either end would put the screen's full paint one byte off the theme's background and
/// nothing on screen would say so.
#[test]
